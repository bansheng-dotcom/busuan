def wx_rel(yong_wx, ti_wx):
    """体用生克关系"""
    sheng = {"木":"火", "火":"土", "土":"金", "金":"水", "水":"木"}  # 我生
    ke = {"木":"土", "土":"水", "水":"火", "火":"金", "金":"木"}      # 我克
    if sheng.get(yong_wx) == ti_wx:
        return "用生体(吉)"
    if sheng.get(ti_wx) == yong_wx:
        return "体生用(泄气)"
    if ke.get(yong_wx) == ti_wx:
        return "用克体(凶)"
    if ke.get(ti_wx) == yong_wx:
        return "体克用(小吉)"
    return "体用比和(吉)"
