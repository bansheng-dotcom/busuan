def _all():
    for cat, entries in _CATS:
        for e in entries:
            yield {"类型": cat, **e}


def lookup(term):
    """精确/包含查（名称精确优先）。"""
    term = term.strip()
    exact = [e for e in _all() if e["名称"] == term]
    if exact:
        return exact[0]
    for e in _all():
        if term in e["名称"] or term in e["断语"]:
            return e
    return None


def search(term, k=5):
    """模糊检索：名称命中 1.0，断语/原文命中 0.5，按分排序。"""
    term = term.strip()
    scored = []
    for e in _all():
        s = 0.0
        if term in e["名称"]:
            s = 1.0
        elif term in e["断语"] or term in e["原文"] or term in e["类型"]:
            s = 0.5
        if s:
            scored.append((s, e))
    scored.sort(key=lambda x: -x[0])
    return [{"score": s, **e} for s, e in scored[:k]]


def to_json():
    import json
    return json.dumps([{"类型": c, "条目": [e for e in es]} for c, es in _CATS], ensure_ascii=False, indent=2)


