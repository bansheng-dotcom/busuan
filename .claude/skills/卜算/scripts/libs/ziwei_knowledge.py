def lookup(term):
    """按关键词检索断语：星名 / 宫名 / 四化名。返回 dict 或 None。"""
    if term in STARS:
        return {"类型": "星曜", "名称": term, **STARS[term], "出处": SRC}
    if term in PALACES:
        return {"类型": "宫位", "名称": term, "主事": PALACES[term], "出处": SRC}
    if term in SIHUA:
        return {"类型": "四化", "名称": term, **SIHUA[term], "出处": SRC}
    # 格局（懒加载 ziwei_geju 的注册表）
    import ziwei_geju
    for p in ziwei_geju._PATTERNS:
        if p["name"] == term:
            return {"类型": "格局", "名称": term, "吉凶": p["吉凶"],
                    "断语": p["断语"], "原文": p["原文"], "出处": p.get("出处", SRC)}
    return None


def _all_entries():
    """知识包全部条目（星曜/宫位/四化/格局），统一成可检索 dict。"""
    entries = []
    for k, v in STARS.items():
        entries.append({"类型": "星曜", "名称": k, "断语": v["断语"],
                        "原文": v.get("原文", ""), "吉凶": "", "出处": SRC})
    for k, v in PALACES.items():
        entries.append({"类型": "宫位", "名称": k, "断语": v,
                        "原文": "", "吉凶": "", "出处": SRC})
    for k, v in SIHUA.items():
        entries.append({"类型": "四化", "名称": k, "断语": v["断语"],
                        "原文": v.get("原文", ""), "吉凶": v["吉凶"], "出处": SRC})
    import ziwei_geju
    for p in ziwei_geju._PATTERNS:
        entries.append({"类型": "格局", "名称": p["name"], "断语": p["断语"],
                        "原文": p["原文"], "吉凶": p["吉凶"], "出处": p.get("出处", SRC)})
    return entries


def search(term, k=5):
    """模糊检索知识包：名称精确(1.0) > 名称包含(0.8) > 断语(0.5) > 原文(0.45)。
    供紫微断卦补断语依据（星曜/宫位/四化/格局），断卦仍须 Grep 原文佐证。"""
    term = (term or "").strip()
    scored = []
    for e in _all_entries():
        s = 0.0
        if term and term == e["名称"]:
            s = 1.0
        elif term in e["名称"]:
            s = 0.8
        elif term in e["断语"]:
            s = 0.5
        elif term in e["原文"]:
            s = 0.45
        if s > 0:
            scored.append((s, e))
    scored.sort(key=lambda x: -x[0])
    return [{"score": round(s, 2), **e} for s, e in scored[:k]]


def to_json():
    """导出全量知识包为 JSON 字符串（喂检索/RAG）。"""
    return json.dumps({
        "星曜": [{"星": k, **v} for k, v in STARS.items()],
        "十二宫": [{"宫": k, "主事": v} for k, v in PALACES.items()],
        "四化": [{"四化": k, **v} for k, v in SIHUA.items()],
        "出处": SRC,
    }, ensure_ascii=False, indent=2)


