def search(kind, name):
    """象法检索：kind ∈ {六神, 六亲}，name ∈ 对应键。返回类象 + 五行 + 吉凶。"""
    table = _LIUSHEN if kind == "六神" else _LIUQIN
    r = table.get(name)
    if not r:
        return None
    return {"kind": kind, "name": name, **r}


def _fmt(r):
    if not r:
        return "（无此条目）"
    wx = f"五行{r['五行']} " if "五行" in r else ""
    jx = f"吉凶{r['吉凶']} " if "吉凶" in r else ""
    return f"{r['kind']}「{r['name']}」{wx}{jx}\n  类象：{'、'.join(r['象'])}\n  用神取法：{r.get('用神', '—')}"


def main():
    for _s in (sys.stdout, sys.stderr):
        try:
            _s.reconfigure(encoding="utf-8")
        except Exception:
            pass
    a = sys.argv[1:]
    if len(a) < 2:
        print(__doc__)
        return
    print(_fmt(search(a[0], a[1])))


if __name__ == "__main__":
    main()
