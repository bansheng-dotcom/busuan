        t = SHEN_SHA_DB["将星"]["表"].get(nian_zhi)
        found = []
        if t and t in zhi_list:
            found.append(f"{t}(年支)")
        t2 = SHEN_SHA_DB["将星"]["表"].get(ri_zhi)
        if t2 and t2 in zhi_list:
            found.append(f"{t2}(日支)")
        if found:
            add("特殊格局", self._mk("将星", found))
        t = SHEN_SHA_DB["国印贵人"]["表"].get(nian_gan)
        if t and t in zhi_list:
            add("特殊格局", self._mk("国印贵人", [t]))

        # —— 凶煞 ——
        t = SHEN_SHA_DB["空亡"]["表"].get(ri_zhu, [])
        if [z for z in zhi_list if z in t]:
            add("凶煞", self._mk("空亡", [z for z in zhi_list if z in t]))
