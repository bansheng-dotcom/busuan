        # —— 禄财 ——
        for name in ("禄神", "金舆"):
            t = SHEN_SHA_DB[name]["表"].get(ri_gan)
            if t and t in zhi_list:
                add("禄财", self._mk(name, [t]))

        # —— 婚姻感情（年支或日支起查） ——
        for name, use_day in (("桃花", True), ("驿马", True)):
            found = []
