# ======================================================================
# 二、旺衰判断（得令 / 得地 / 得生 / 得助）—— 能写死的部分
# ======================================================================
# 说明：本函数只做「确定性粗筛」，输出四项硬指标——
#       得令用五行生克法（月支生/同 日主）；得地=四支藏干见比劫（未分本气/中气/余气、
#       未计冲克合化空亡削弱）。最终「身强/身弱/中和」的综合结论涉及权重权衡与根气复核，
#       见「规则约束.md」与 SKILL.md 步骤 1，不在此强行代码化。

YIN = ("正印", "偏印")        # 印星（生我）
BI_JIE = ("比肩", "劫财")     # 比劫（同我）


def analyze_wangshuai(year, month, day, hour, gender, minute=0):
    """旺衰四指标分析（确定性判断）。

    返回：
      - 日主、日主五行、月令地势
      - 得令：日主是否得月令生扶
      - 得地：日主在地支是否有根（藏干见比劫）
      - 得生：四柱是否有印星生扶
      - 得助：四柱是否有比劫帮扶
    """
    solar = Solar.fromYmdHms(year, month, day, hour, minute, 0)
    ec = solar.getLunar().getEightChar()

    ri_gan = ec.getDayGan()                    # 日主
    ri_wx = gan_wuxing(ri_gan)                 # 日主五行
    yue_zhi = ec.getMonthZhi()                 # 月支
    yue_wx = ZHI_WUXING[yue_zhi]               # 月支五行
    dishi = ec.getMonthDiShi()                 # 日主在月支的十二长生地势

    # 得令：月支生扶日主（印生 或 比劫同类）
    rel = sheng_ke(yue_wx, ri_wx)
    de_ling = rel in ("a生b", "同类")

    # 藏干十神（四支）
    shishen_zhis = [
        ec.getYearShiShenZhi(), ec.getMonthShiShenZhi(),
        ec.getDayShiShenZhi(), ec.getTimeShiShenZhi(),
    ]
    zhi_shishen = [s for lst in shishen_zhis for s in lst]

    # 天干十神（年/月/时干，排除日主）
    shishen_gans = [
        ec.getYearShiShenGan(), ec.getMonthShiShenGan(), ec.getTimeShiShenGan(),
    ]

    # 得地：地支藏干有比劫（有根）
    de_di = any(s in BI_JIE for s in zhi_shishen)
    # 得生：天干或藏干有印星
    de_sheng = any(s in YIN for s in shishen_gans + zhi_shishen)
    # 得助：天干或藏干有比劫
    de_zhu = any(s in BI_JIE for s in shishen_gans + zhi_shishen)

    return {
        "日主": ri_gan,
        "日主五行": ri_wx,
        "月支": yue_zhi,
        "月支五行": yue_wx,
        "月令地势": dishi,
        "得令": de_ling,
        "得地": de_di,
        "得生": de_sheng,
        "得助": de_zhu,
    }


# ======================================================================
# 三、格局判定（《子平真诠》月令定格）—— 能写死的部分
# ======================================================================
# 说明：只做「月令定格」的确定性判定（月支本气/透干 → 格）。
#       格局的「成败救应」（如正官格逢伤官则败）见「规则约束.md」。

def ding_ge(year, month, day, hour, gender, minute=0):
    """月令定格（《子平真诠》）。

    规则：
      1. 取月支藏干（本气、中气、余气）及其十神；
      2. 月支本气十神 = 基础格；
      3. 若月支藏干透出天干（年月时干），以透出之十神定格；
      4. 月支为日主「临官」→ 建禄格；「帝旺」→ 羊刃格。
    返回：格局名 + 判定依据。
    """
    solar = Solar.fromYmdHms(year, month, day, hour, minute, 0)
    ec = solar.getLunar().getEightChar()

    ri_gan = ec.getDayGan()
    dishi = ec.getMonthDiShi()

    # 建禄格 / 羊刃格（羊刃仅阳干：甲丙戊庚壬，阴干帝旺不称羊刃）
    if dishi == "临官":
        return {"格局": "建禄格", "依据": "月支为日主临官（禄）"}
    if dishi == "帝旺" and ri_gan in ("甲", "丙", "戊", "庚", "壬"):
        return {"格局": "羊刃格", "依据": f"月支为日主{ri_gan}帝旺（阳刃）"}

    # 月支藏干 + 十神
    hide_gans = ec.getMonthHideGan()           # 月支藏干（本气在前）
    shishen_zhi = ec.getMonthShiShenZhi()       # 对应十神

    # 天干（年月时干）十神
    tian_gans = {
        "年": ec.getYearGan(), "月": ec.getMonthGan(), "时": ec.getTimeGan(),
    }
    tian_shishen = {
        "年": ec.getYearShiShenGan(), "月": ec.getMonthShiShenGan(), "时": ec.getTimeShiShenGan(),
    }

    # 判断月支藏干是否透出天干
    base_ge = shishen_zhi[0] if shishen_zhi else None   # 本气十神
    ge = base_ge
    ge_yiju = f"月支本气{hide_gans[0] if hide_gans else ''}({base_ge})"

    # 若本气未透，看中气/余气透出者
    for i, (hg, ss) in enumerate(zip(hide_gans, shishen_zhi)):
        if hg in tian_gans.values():
            ge = ss
            ge_yiju = f"月支藏干{hg}({ss})透干"
            break

    return {"格局": ge, "依据": ge_yiju}
