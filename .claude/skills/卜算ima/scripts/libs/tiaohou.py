def sheng_ke(a, b):
    """两五行生克关系 -> 'a生b'/'a克b'/'b生a'/'b克a'/'同类'"""
    if a == b:
        return "同类"
    if SHENG.get(a) == b:
        return "a生b"
    if SHENG.get(b) == a:
        return "b生a"
    if KE.get(a) == b:
        return "a克b"
    if KE.get(b) == a:
        return "b克a"
    return "未知"


