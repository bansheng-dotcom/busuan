def tianjiang(name):
    """十二天将吉凶。R-LR-TJ"""
    j, m = TIANJIANG.get(name, ("中", "未明"))
    return {"吉凶": j, "主事": m, "出处": f"{SOURCE}·十二天将"}


def _xun_shou(day_gan, day_zhi):
    """旬首：日干逆数到甲，同时日支逆数相应位。"""
    gans = "甲乙丙丁戊己庚辛壬癸"
    gi = gans.index(day_gan)
    zi = _ZHI.index(day_zhi)
    return gans[0], _ZHI[(zi - gi) % 12]


def compute_shensha(day_gan, day_zhi, year_zhi, month_zhi, month=1):
    """计算命中神煞。返回 {神煞名: {地支, 吉凶, 出处}}。

    month 为农历月（1-12），用于天德（省略，仅给月德）。year_zhi/month_zhi 为年支/月支。
    """
    hits = {}
    ju = _SANHE.get(year_zhi)
    if ju:
        for name, zhi in _SHEN[ju].items():
            if zhi == day_zhi:
                hits[name] = {"地支": zhi, "吉凶": _SHEN_JX[name], "出处": f"{SOURCE}·神煞"}

    # 日干神煞（日德/日禄/羊刃落支；天乙贵人以日支入）
    gs = _GAN_SHEN.get(day_gan, {})
    for name in ("日德", "日禄", "羊刃"):
        if gs.get(name) == day_zhi:
            hits[name] = {"地支": day_zhi, "吉凶": _GAN_SHEN_JX[name], "出处": f"{SOURCE}·神煞"}
    if day_zhi in gs.get("天乙", ()):
        hits["天乙贵人"] = {"地支": day_zhi, "吉凶": "吉", "出处": f"{SOURCE}·神煞"}

    # 月德（月支定，看日干是否值）
    if _YUEDE.get(month_zhi) == day_gan:
        hits["月德"] = {"地支": day_zhi, "吉凶": "吉", "出处": f"{SOURCE}·神煞"}

    # 天喜/红鸾（月支定，看日支是否值）
    tx = _TIANXI.get(month_zhi)
    if tx:
        if tx == day_zhi:
            hits["天喜"] = {"地支": day_zhi, "吉凶": "吉", "出处": f"{SOURCE}·神煞"}
        if _ZHI[(_ZHI.index(tx) + 6) % 12] == day_zhi:
            hits["红鸾"] = {"地支": day_zhi, "吉凶": "吉", "出处": f"{SOURCE}·神煞"}

    # 旬空（日支落旬空）
    xk = _XUNKONG.get(_xun_shou(day_gan, day_zhi))
    if xk and day_zhi in xk:
        hits["旬空"] = {"地支": day_zhi, "吉凶": "凶", "出处": f"{SOURCE}·神煞"}

    # —— 扩展神煞 ——
    # 天德（干或四维支）
    tg, tz = _TIANDE.get(month_zhi, (None, None))
    if tg == day_gan or (tz and tz == day_zhi):
        hits["天德"] = {"地支": day_zhi, "吉凶": "吉", "出处": f"{SOURCE}·神煞"}
    # 天马/生气/死气/天医/月厌/皇恩（月支 -> 落支，看日支）
    for name, table in (("天马", _TIANMA), ("生气", _SHENGQI), ("死气", _SIQI),
                        ("天医", _TIANYI), ("月厌", _YUEYAN), ("皇恩", _HUANGEN)):
        if table.get(month_zhi) == day_zhi:
            hits[name] = {"地支": day_zhi, "吉凶": _EXT_JX[name], "出处": f"{SOURCE}·神煞"}
    # 游都 / 鲁都（日干）
    yd = _YOUDU.get(day_gan)
    if yd == day_zhi:
        hits["游都"] = {"地支": day_zhi, "吉凶": "凶", "出处": f"{SOURCE}·神煞"}
    if yd and _chong(yd) == day_zhi:
        hits["鲁都"] = {"地支": day_zhi, "吉凶": "凶", "出处": f"{SOURCE}·神煞"}
    # 五墓（日干五行墓）
    if _WUMU.get(day_gan) == day_zhi:
        hits["五墓"] = {"地支": day_zhi, "吉凶": "凶", "出处": f"{SOURCE}·神煞"}
    # 岁破 / 月破（对冲）
    if _chong(year_zhi) == day_zhi:
        hits["岁破"] = {"地支": day_zhi, "吉凶": "凶", "出处": f"{SOURCE}·神煞"}
    if _chong(month_zhi) == day_zhi:
        hits["月破"] = {"地支": day_zhi, "吉凶": "凶", "出处": f"{SOURCE}·神煞"}
    # 天罗（辰）/ 地网（戌）
    if day_zhi == "辰":
        hits["天罗"] = {"地支": "辰", "吉凶": "凶", "出处": f"{SOURCE}·神煞"}
    if day_zhi == "戌":
        hits["地网"] = {"地支": "戌", "吉凶": "凶", "出处": f"{SOURCE}·神煞"}
    # 天赦 / 四废（季节 + 日干支）
    season = _SEASON.get(month_zhi)
    if season and _TIANSHE.get(season) == day_gan + day_zhi:
        hits["天赦"] = {"地支": day_zhi, "吉凶": "吉", "出处": f"{SOURCE}·神煞"}
    if season and (day_gan + day_zhi) in _SIFEI.get(season, ()):
        hits["四废"] = {"地支": day_zhi, "吉凶": "凶", "出处": f"{SOURCE}·神煞"}

    return hits


def format_shensha(hits):
    """格式化神煞命中输出。"""
    if not hits:
        return "  （无核心神煞命中）"
    lines = []
    for name, v in hits.items():
        lines.append(f"  · {name}（{v['地支']}，{v['吉凶']}，出处：{v['出处']}）")
    return "\n".join(lines)


