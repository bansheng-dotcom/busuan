def lookup(keyword="", jx=None):
    """检索毕法赋条目。keyword 在赋文句/主断方向中匹配；jx 过滤吉凶档（吉/凶/中）。"""
    out = []
    for ju, j, d in BIFA:
        if jx and j != jx:
            continue
        if keyword and keyword not in ju and keyword not in d:
            continue
        out.append({"句": ju, "吉凶": j, "主断": d, "出处": SOURCE})
    return out


def jx_to_judgment(jx):
    """三档吉凶归一（供 cross_validate）：吉->吉，凶->凶，中->中。"""
    return jx if jx in ("吉", "凶", "中") else "中"


def completeness():
    """校验条目：无重复、无空字段。"""
    names = [b[0] for b in BIFA]
    dup = [n for n in set(names) if names.count(n) > 1]
    empty = [b for b in BIFA if not all(b)]
    return len(BIFA), dup, empty


