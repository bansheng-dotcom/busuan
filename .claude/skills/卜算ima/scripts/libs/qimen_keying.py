def lookup(tianpan, dipan):
    """查十干克应。返回 {格局, 吉凶, 含义, 出处}。非具名组合返回 格局=None。"""
    hit = KEYING.get((tianpan, dipan))
    if not hit:
        return {"格局": None, "吉凶": "中", "含义": "非十干克应具名组合", "出处": SOURCE}
    name, jx, yi = hit
    return {"格局": name, "吉凶": jx, "含义": yi, "出处": SOURCE}


def jx_to_judgment(jx):
    """五档吉凶归一化为三档（吉/凶/中），供 cross_validate 使用。"""
    if "吉" in jx and "凶" not in jx:
        return "吉"
    if "凶" in jx and "吉" not in jx:
        return "凶"
    return "中"


