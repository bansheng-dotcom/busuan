# -*- coding: utf-8 -*-
"""排盘 gate 预检：断卦前必查。任一必查项缺失即停下补齐，不得跳过直接断卦。

对应 SKILL.md 第六节「排盘自检清单（强制 gate）」。
"""

GATE = {
    "小六壬": ["落宫"],
    "梅花易数": ["本卦", "互卦", "变卦", "动爻", "体用"],
    "六爻纳甲": ["六爻", "纳甲", "世应", "六亲", "六神"],
    "大六壬": ["天地盘", "四课", "三传", "天将"],
    "奇门遁甲": ["排局", "三奇六仪", "九星", "八门", "八神"],
    "太乙神数": ["积年", "行宫", "主客算"],
    "八字": ["四柱", "十神", "五行", "纳音", "大运"],
    "紫微斗数": ["命宫", "身宫", "五行局", "十二宫", "四化", "大限"],
    "七政四余": ["七政", "四余", "十二宫"],
    "风水堪舆": ["命卦", "宅型", "飞星"],
    "择日": ["建除", "黄道", "神煞"],
}


def gate(术, fields):
    """检查必查项。fields: 已具备的字段名集合。返回缺失列表。"""
    req = GATE.get(术, [])
    return [f for f in req if f not in fields]


def check(术, fields):
    """gate 判定。缺失为空则通过，否则列出缺失并返回 False。"""
    missing = gate(术, fields)
    if missing:
        return False, f"缺 {', '.join(missing)}"
    return True, "通过"
