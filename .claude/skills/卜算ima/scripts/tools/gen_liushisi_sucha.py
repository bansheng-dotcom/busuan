def shang_xia_rel(sw, xw):
    """上卦五行 vs 下卦五行 -> 生克关系（体用需按动爻定，此为上下卦生克参考）"""
    if sw == xw:
        return "上下比和"
    if _KE.get(sw) == xw:
        return "上克下"
    if _KE.get(xw) == sw:
        return "下克上"
    if _SHENG.get(sw) == xw:
        return "上生下"
    if _SHENG.get(xw) == sw:
        return "下生上"
    return "未明"


