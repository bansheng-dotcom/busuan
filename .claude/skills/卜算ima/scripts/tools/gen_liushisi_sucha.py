def _clean(s):
    """清理原文：去空白、引号、书名号，压成一段"""
    s = re.sub(r"[「」『』“”《》]", "", s)
    s = re.sub(r"\s+", "", s)
    return s.strip()


def extract_all():
    """提取每卦的卦辞、彖传、大象传（原文）"""
    lines = open(ZHOUYI_TXT, encoding="utf-8").read().splitlines()
    # 定位卦名行
    gua_lines = []  # (name, line_index)
    for i, line in enumerate(lines):
        m = re.match(r"\s*《?([^》》\s]+)》?[：:]\s*(.*)", line)
        if m:
            name = ALIAS.get(m.group(1).strip(), m.group(1).strip())
            if name in ORDER:
                gua_lines.append((name, i))
    result = {}
    for j, (name, idx) in enumerate(gua_lines):
        end = gua_lines[j + 1][1] if j + 1 < len(gua_lines) else len(lines)
        block = "\n".join(lines[idx:end])
        # 卦辞（该卦首行「X：…」）
        m = re.match(r"\s*《?[^》》\s]+》?[：:]\s*(.*)", lines[idx])
        ci = m.group(1).strip() if m else ""
        ci = re.split(r"《彖》|《象》|《文言》|《系辞》", ci)[0]
        ci = re.split(r"初[六九]|九[一二三四五六]|六[一二三四五六]|上[六九]|用[六九]", ci)[0]
        # 彖传（《彖》曰 到 《象》曰）
        tm = re.search(r"《彖》曰[：:]?\s*(.*?)(?=《象》曰)", block, re.S)
        tuan = _clean(tm.group(1)) if tm else ""
        # 大象传（《象》曰 后第一个「…君子以…。」句）
        xm = re.search(r"《象》曰[：:]?\s*(.*?君子以[^。]*。)", block, re.S)
        xiang = _clean(xm.group(1)) if xm else ""
        result[name] = {"guaci": _clean(ci), "tuan": tuan, "xiang": xiang}
    return result


