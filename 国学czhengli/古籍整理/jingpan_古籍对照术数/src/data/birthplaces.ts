export const DEFAULT_BIRTHPLACE_PATH = ['北京市', '市轄區', '東城區'];

export interface BirthplaceHit {
  path: string[];
  label: string;
  lng: number;
  lat: number;
}

export function findPlaceByPath(path: string[]): BirthplaceHit | undefined {
  if (!path.length) return undefined;
  let nodes: BirthplaceNode[] | undefined = BIRTHPLACE_TREE;
  let current: BirthplaceNode | undefined;
  for (const key of path) {
    current = nodes?.find((n) => n.name === key);
    if (!current) return undefined;
    nodes = current.children;
  }
  if (current?.lng === undefined || current.lat === undefined) return undefined;
  return {
    path,
    label: path.filter((n) => n !== '市轄區').join(' '),
    lng: current.lng,
    lat: current.lat,
  };
}

export function getDefaultBirthplace(): BirthplaceHit {
  return findPlaceByPath(DEFAULT_BIRTHPLACE_PATH)!;
}
