/** 出生地三级：省 → 市 → 區（大城市到主城區）。葉節點含經緯度，供真太陽時使用。 */

export interface BirthplaceNode {
  name: string;
  lng?: number;
  lat?: number;
  children?: BirthplaceNode[];
}

type Coord = [string, number, number];

function districts(items: Coord[]): BirthplaceNode[] {
  return items.map(([name, lng, lat]) => ({ name, lng, lat }));
}

function city(name: string, lng: number, lat: number, items?: Coord[]): BirthplaceNode {
  return {
    name,
    children: items?.length ? districts(items) : [{ name: '市區', lng, lat }],
  };
}

function province(name: string, cities: BirthplaceNode[]): BirthplaceNode {
  return { name, children: cities };
}

